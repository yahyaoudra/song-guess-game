export const MOROCCAN_SONGS = ALL_SONGS;

export function getSongsForCountry(countryCode?: string): Song[] {
  if (!countryCode || countryCode === 'GLOBAL') {
    return ALL_SONGS;
  }
  const countrySongs = ALL_SONGS.filter(s => s.countryCode === countryCode);
  if (countrySongs.length >= 5) {
    return countrySongs;
  }
  // Return country songs if any, otherwise fallback to GLOBAL hits (never wrong country)
  const globalHits = ALL_SONGS.filter(s => s.countryCode === 'GLOBAL' || s.countryCode === 'US' || s.countryCode === 'GB');
  return countrySongs.length > 0 ? countrySongs : globalHits;
}

